/**
 * 相談先案内の表現リスト。自分や子どもを傷つけそうな気持ちのほのめかしを、ローカルで検出する。
 *
 * OpenAI Moderationは、子どもへの加害の不安（「手を上げてしまいそうで怖い」等）を検知しないことが
 * 実測で分かった（全カテゴリ 0.00〜0.02）。そのため、APIの判定に加えて、この表現リストでも案内を出す。
 *
 * 用途は「止める」ことではなく、書いた本人にだけ相談先を案内すること（決定済み）。誤検出しても害が
 * 小さい（支える方向の表示）ため、漏れを減らす側に寄せる。ただし、日常の言い回し（「手を上げて横断歩道を
 * わたった」など）には反応しないよう、気持ちを表す語を伴う並びに限る。
 * 初期版の起点で、実例を見て追加・調整する（docs/送信前チェック評価.md）。入力は、NFKC正規化済みの文字列。
 */
export const SUPPORT_PATTERNS: readonly RegExp[] = [
  // 自分の消えたい気持ち・生きるつらさ
  /死にたい|消えたい|いなくなりたい|消えてしまいたい|消えてなくなりたい|生きていたくない/,
  /生きて(?:い)?(?:る|く)のが(?:つらい|辛い|しんどい|苦しい|嫌|いや)/,
  /(?:もう|本当に|ほんとに).{0,6}(?:死んで|消えて)(?:しまい|楽に)/,
  // 子どもへの加害の不安・加害してしまったこと
  /(?:子ども|子供|息子|娘|赤ちゃん|我が子|わが子).{0,8}(?:手を上げ|手をあげ|叩い|たたい|殴っ|殴り|蹴っ|蹴り|当たっ|あたっ|傷つけ).{0,6}(?:しまい|しまった|そう)/,
  /(?:手を上げ|手をあげ|叩い|たたい|殴っ|殴り|当たっ|あたっ)て?しまい(?:そう|たく)/,
  /(?:虐待|傷つけて)(?:して)?しまい(?:そう|たく)/,
  /育てられない.{0,12}(?:いなくなり|消え|死に)/,
];

export function needsSupportNotice(normalizedText: string): boolean {
  return SUPPORT_PATTERNS.some((p) => p.test(normalizedText));
}
